import math

# =====================================================================
# 1. Физические свойства магнитной жидкости (СИ)
# =====================================================================
# Типичные параметры для Fe3O4
rho = 1400.0          # Плотность, кг/м^3
nu = 1.0e-6           # Кинематическая вязкость, м^2/с (при ~3-4 мПа*с)
sigma = 0.025         # Поверхностное натяжение (alpha в формуле), Н/м
chi = 1               # Магнитная восприимчивость (безразмерная)
mu_0 = 4.0 * math.pi * 1e-7  # Магнитная постоянная, Гн/м (Тл*м/А)
# =====================================================================
# 2. Характерные геометрические и внешние параметры
# =====================================================================
c_0 = 1e-4   # Характерная толщина слоя, м
g = 9.81     # Ускорение свободного падения, м/с^2

# Параметры колебаний (вибраций)
a_amp = c_0 * 10  # Амплитуда колебаний, м
f_hz = 100.0  # Частота колебаний, Гц
Omega = 100  # Круговая частота, рад/с

# Магнитное поле
H_0 = 10000.0         # Напряжённость магнитного поля, А/м


# =====================================================================
# [Капиллярное число]
Ca_star = (sigma * c_0) / (rho * (nu ** 2))

# [Число Галилея]
G = (g * (c_0 ** 3)) / (nu ** 2)

# Безразмерная амплитуда]
b_star = a_amp / c_0

# [Безразмерная частота]
omega = ((c_0 ** 2) / nu) * Omega

# Ha = (mu_0 * chi * c_0^2 * H_0^2) / (rho * nu^2) [Аналог числа Гартмана / магн. параметр]
Ha = (mu_0 * chi * (c_0 ** 2) * (H_0 ** 2)) / (rho * (nu ** 2))


# =====================================================================
print("--- Оценка безразмерных параметров ---")
print(f"Толщина слоя c0:        {c_0} м")
print(f"Амплитуда колебаний a:  {a_amp} м")
print(f"Частота Omega:              {f_hz:.1f}  рад/с)")
print(
    f"Поле H0:                {H_0:.0f} А/м (B0 ~ {mu_0 * H_0 * 1000:.2f} мТл)")
print("-" * 38)
print(f"Ca* (Капиллярное число)         = {Ca_star:.4e}")
print(f"G   (Число Галилея)            = {G:.4e}")
print(f"b*  (Амплитуда колебаний)      = {b_star:.4e}")
print(f"omega (Частота колебаний)      = {omega:.4e}")
print(f"Ha  (Магнитный параметр)       = {Ha:.4e}")
